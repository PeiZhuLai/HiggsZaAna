#!/bin/bash
# Recompute the observed (unblinded, real SR data) AsymptoticLimits with the current production
# datacards (xsec and Wilson cards, mA 1-30) and redraw the plots in
# /eos/home-p/pelai/HZa/output_plots/limits_observed_20261026.
#
# Combine options are identical to the production expected limits (deploy chain stage 4)
# except that --run blind is dropped: --cminDefaultMinimizerStrategy 0 -m 125.38
# --setParameters MH=125.38 --freezeParameters MH --rMax 2, run directly on the datacard.
# The plot command is the one that produced limits_observed_20261026 (unblind_prep step 3).
#
# Old outputs are moved, not deleted:
#   Combine/output_combine_results_observed{,_wilson} -> ..._preDeployMA11_12ps
#   EOS limits_observed_20261026 -> copied to limits_observed_20261026_bak_preDeployMA11_12ps
# lowmass_obs_rhat_vs_closure.txt in the EOS dir is not regenerated by this script.
#
# Usage: bash run_observed.sh        (dry-run)
#        GO=1 bash run_observed.sh   (run)
set -u
D=$(cd "$(dirname "$0")" && pwd)
FF=/afs/cern.ch/work/p/pelai/HZa/flashgg_run3/CMSSW_14_1_0_pre4/src/flashggFinalFit
C=$FF/Combine
DC=$FF/Datacard/output_Datacard_leptons
EOSD=/eos/home-p/pelai/HZa/output_plots/limits_observed_20261026
SFX=preDeployMA11_12ps
L=$D/logs
NPROC=${NPROC:-4}
MASSES=${MASSES:-$(seq 1 30)}
GO=${GO:-0}

for m in $MASSES; do for s in "" _xsec; do
  [ -s $DC/${m}_pruned_datacard_leptons$s.txt ] || { echo "missing datacard mA$m$s"; exit 1; }
done; done
if [ "$GO" != 1 ]; then
  echo "DRY-RUN: $(echo $MASSES | wc -w) masses x 2 cards, $NPROC parallel, logs -> $L"
  echo "  move $C/output_combine_results_observed{,_wilson} -> *_$SFX"
  echo "  copy $EOSD -> ${EOSD}_bak_$SFX ; plots -> $EOSD"
  exit 0
fi
mkdir -p $L $D/work
rm -f $L/*.DONE $L/*.FAIL
for k in "" _wilson; do
  src=$C/output_combine_results_observed$k; dst=${src}_$SFX
  [ -e $dst ] && { echo "backup exists: $dst"; exit 1; }
  mv $src $dst && mkdir -p $src || exit 1
done
[ -e ${EOSD}_bak_$SFX ] && { echo "EOS backup exists"; exit 1; }
cp -a $EOSD ${EOSD}_bak_$SFX || exit 1

set +u; source /cvmfs/cms.cern.ch/cmsset_default.sh; cd $FF/.. && eval $(scramv1 runtime -sh); set -u

obs_one() {
  local m=$1 k=$2 s="" out=$C/output_combine_results_observed_wilson W
  [ $k = xsec ] && { s=_xsec; out=$C/output_combine_results_observed; }
  W=$D/work/obs_${k}_$m; rm -rf $W; mkdir -p $W; cd $W
  if combine -M AsymptoticLimits $DC/${m}_pruned_datacard_leptons$s.txt --cminDefaultMinimizerStrategy 0 -m 125.38 \
       --setParameters MH=125.38 --freezeParameters MH --rMax 2 -n $m > $L/obs_${k}_$m.log 2>&1 \
     && mv higgsCombine$m.AsymptoticLimits.mH125.38.root $out/; then
    touch $L/obs_${k}_$m.DONE
  else
    touch $L/obs_${k}_$m.FAIL
  fi
}
export -f obs_one; export C D DC L
echo "[$(date '+%F %T')] observed limits start"
for m in $MASSES; do printf '%s xsec\n%s wilson\n' $m $m; done | xargs -P$NPROC -L1 bash -c 'obs_one $0 $1'
nf=$(ls $L/*.FAIL 2>/dev/null | wc -l); nd=$(ls $L/obs_*.DONE 2>/dev/null | wc -l)
echo "[$(date '+%F %T')] combine done: $nd ok, $nf failed"
[ $nf -eq 0 ] || { echo "FAILED jobs, plots not redrawn"; touch $L/ALL.FAIL; exit 1; }

( cd $FF/Plots && python3 makeLimitsPlot.py --outdir $EOSD --assume-xs 100 --higgs-xs 59703.914 --lumi 172.13 --formats pdf,png \
    --masses $(seq -s, 1 30) --only xs,br,wilson,compare \
    --results-dir $C/output_combine_results_observed --results-dir-wilson $C/output_combine_results_observed_wilson --tag-suffix _observed ) \
  > $L/limits_plot.log 2>&1 || { echo "plot failed ($L/limits_plot.log)"; touch $L/ALL.FAIL; exit 1; }
echo "[$(date '+%F %T')] plots -> $EOSD"
touch $L/ALL.DONE
